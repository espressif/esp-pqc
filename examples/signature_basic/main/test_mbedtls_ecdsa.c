typedef struct {
    uint64_t total_cycles;
    uint64_t min_cycles;
    uint64_t max_cycles;
    uint64_t total_time_us;
    uint64_t min_time_us;
    uint64_t max_time_us;
    uint32_t count;
} ecdsa_perf_stats_t;


/* PSA-based ECDSA verify (aligned with test_psa_ecdsa.c). */
void test_ecdsa_verify(ecdsa_curve_t curve, const uint8_t *hash, const uint8_t *r_comp, const uint8_t *s_comp,
                       const uint8_t *pub_x, const uint8_t *pub_y)
{
    ecdsa_perf_stats_t stats = {
        .min_cycles = UINT64_MAX, .min_time_us = UINT64_MAX,
        .max_cycles = 0, .max_time_us = 0,
        .total_cycles = 0, .total_time_us = 0,
        .count = 0
    };
    const int iterations = 20;

    size_t hash_len = 0;
    size_t plen = 0;

    switch (curve) {
        case ECDSA_CURVE_SECP192R1:
            plen = 192;
            hash_len = HASH_LEN;
            break;
        case ECDSA_CURVE_SECP256R1:
            plen = 256;
            hash_len = HASH_LEN;
            break;
#if SOC_ECDSA_SUPPORT_CURVE_P384
        case ECDSA_CURVE_SECP384R1:
            plen = 384;
            hash_len = HASH_LEN_P384;
            break;
#endif
        default:
            printf("ECDSA Verify Fail: invalid curve\n");
            return;
    }

    size_t plen_bytes = plen / 8;

    /* Build uncompressed public key: 0x04 || x || y (as in test_psa_ecdsa.c). */
    uint8_t psa_key[2 * MAX_ECDSA_COMPONENT_LEN + 1];
    size_t psa_key_len = 2 * plen_bytes + 1;
    psa_key[0] = ECDSA_UNCOMPRESSED_POINT_FORMAT;
    memcpy(psa_key + 1, pub_x, plen_bytes);
    memcpy(psa_key + 1 + plen_bytes, pub_y, plen_bytes);

    psa_key_attributes_t key_attr = PSA_KEY_ATTRIBUTES_INIT;
    psa_set_key_type(&key_attr, PSA_KEY_TYPE_ECC_PUBLIC_KEY(PSA_ECC_FAMILY_SECP_R1));
    psa_set_key_usage_flags(&key_attr, PSA_KEY_USAGE_VERIFY_HASH);
    psa_set_key_algorithm(&key_attr, PSA_ALG_ECDSA(PSA_ALG_SHA_256));
    psa_set_key_bits(&key_attr, plen);

    psa_key_id_t key_id = 0;
    psa_status_t status = psa_import_key(&key_attr, psa_key, psa_key_len, &key_id);
    psa_reset_key_attributes(&key_attr);
    if (status != PSA_SUCCESS) {
        printf("ECDSA Verify Fail: psa_import_key 0x%x\n", (unsigned)status);
        return;
    }

    uint8_t signature[2 * MAX_ECDSA_COMPONENT_LEN];
    memcpy(signature, r_comp, plen_bytes);
    memcpy(signature + plen_bytes, s_comp, plen_bytes);
    size_t signature_len = 2 * plen_bytes;

    for (int i = 0; i < iterations; i++) {
        uint64_t start_cycles = esp_cpu_get_cycle_count();
        int64_t start_time = esp_timer_get_time();

        status = psa_verify_hash(key_id, PSA_ALG_ECDSA(PSA_ALG_SHA_256), hash, hash_len, signature, signature_len);

        uint64_t end_cycles = esp_cpu_get_cycle_count();
        int64_t end_time = esp_timer_get_time();

        if (status == PSA_SUCCESS) {
            uint64_t diff_cycles = (end_cycles >= start_cycles) ? (end_cycles - start_cycles) : (UINT64_MAX - start_cycles + end_cycles + 1);
            uint64_t diff_time = (uint64_t)(end_time - start_time);
            if (diff_cycles < 50000000ULL) {
                stats.total_cycles += diff_cycles;
                stats.total_time_us += diff_time;
                if (diff_cycles < stats.min_cycles) stats.min_cycles = diff_cycles;
                if (diff_cycles > stats.max_cycles) stats.max_cycles = diff_cycles;
                if (diff_time < stats.min_time_us) stats.min_time_us = diff_time;
                if (diff_time > stats.max_time_us) stats.max_time_us = diff_time;
                stats.count++;
            }
        } else {
            printf("ECDSA Verify Fail: 0x%x\n", (unsigned)status);
            break;
        }
    }

    psa_destroy_key(key_id);

    if (stats.count > 0) {
        const char *curve_name = "";
        if (curve == ECDSA_CURVE_SECP192R1) curve_name = "P-192";
        else if (curve == ECDSA_CURVE_SECP256R1) curve_name = "P-256";
        else if (curve == ECDSA_CURVE_SECP384R1) curve_name = "P-384";
        printf("\n--- ECDSA Verify Performance (Curve: %s) ---\n", curve_name);
        printf("Iterations: %lu\n", (unsigned long)stats.count);
        printf("Time (us) | Avg: %llu, Min: %llu, Max: %llu\n", (unsigned long long)(stats.total_time_us / stats.count), stats.min_time_us, stats.max_time_us);
        printf("Cycles    | Avg: %llu, Min: %llu, Max: %llu\n", (unsigned long long)(stats.total_cycles / stats.count), stats.min_cycles, stats.max_cycles);
    }
}

void test_case_192(void)
{
    test_ecdsa_verify(ECDSA_CURVE_SECP192R1, sha, ecdsa192_r, ecdsa192_s,
                     ecdsa192_pub_x, ecdsa192_pub_y);
}

